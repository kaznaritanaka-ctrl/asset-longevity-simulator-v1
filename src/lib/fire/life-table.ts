const LAST = EX_MALE.length - 1;

function clampAge(age: number): number {
  return Math.min(LAST, Math.max(0, Math.round(age)));
}

export function remainingLife(age: number, sex: Sex): number {
  const i = clampAge(age);
  const table = sex === "female" ? EX_FEMALE : EX_MALE;
  return table[i] ?? 0;
}

export function expectedDeathAge(age: number, sex: Sex): number {
  return age + remainingLife(age, sex);
}

export function lifeSurvival(fromAge: number, atAge: number, sex: Sex): number {
  if (atAge <= fromAge) return 1;
  const lx = sex === "female" ? LX_FEMALE : LX_MALE;
  const a0 = clampAge(fromAge);
  const base = lx[a0] ?? 1;
  if (base <= 0) return 0;
  if (atAge > LAST) return 0;
  const a1 = clampAge(atAge);
  return Math.min(1, Math.max(0, (lx[a1] ?? 0) / base));
}

export function assetHalfLifeAge(ages: number[], survival: number[]): number | null {
  for (let i = 0; i < ages.length; i++) {
    if ((survival[i] ?? 1) <= 0.5) return ages[i] ?? null;
  }
  return null;
}

/** 生存曲線の下の面積。地平で打ち切りなら下限。 */
export function meanAssetYears(survival: number[]): number {
  if (survival.length === 0) return 0;
  let area = 0;
  for (let i = 0; i < survival.length - 1; i++) {
    area += ((survival[i] ?? 0) + (survival[i + 1] ?? 0)) / 2;
  }
  return area;
}
